public class Operator02 {

    public static void main(String[] args) {
        int a=60;
        int b=20;
        int c=10;
        int d=25;

        System.out.println("\nAritmatika Operator");
        System.out.println("Bilangan a adalah " +a);
        System.out.println("Bilangan b adalah " +b);
        System.out.println("Bilangan c adalah " +c);
        System.out.println("Bilangan d adalah " +d);
        System.out.println("(a + b ) * ( c + d ) =" +(a+b)*(c+d));
        System.out.println("a + b + c + d = " +(a+b+c+d));
        System.out.println("a - b - c - d = " +(a-b-c-d));
        System.out.println("a x d = " +(a*d));
        System.out.println("a / d = " +(a/d));
        System.out.println("a % d = " +(a%d));
        System.out.println("a + b x c = " +(a+b*c));
        System.out.println("(a + b) x c = " +((a+b)*c));
        
    }
}